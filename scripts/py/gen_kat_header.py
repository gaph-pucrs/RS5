#!/usr/bin/env python3
"""Generate sw/common/include/mlkem512_kat_values.h from the official KAT responses.

Usage: gen_kat_header.py <PQCkemKAT_1632.rsp> <out.h> [max_count=9]
The header defines KYBER_KAT_{SEED,PK,SK,CT,SS} for the vector selected at compile time with
-DKAT_COUNT=<k> (default 0). kyber_KAT.c draws the k-th 48-byte seed from the NIST DRBG seeded
with entropy 0..47, exactly as PQCgenKAT_kem does for count k.
"""
import sys

rsp, out = sys.argv[1], sys.argv[2]
nmax = int(sys.argv[3]) if len(sys.argv) > 3 else 9
vec, cur = {}, None
for line in open(rsp):
    if ' = ' not in line:
        continue
    k, v = line.strip().split(' = ', 1)
    if k == 'count':
        cur = int(v); vec[cur] = {}
    elif cur is not None:
        vec[cur][k] = v
with open(out, 'w') as fo:
    fo.write('// ML-KEM-512 (FIPS 203) KAT vectors, count = 0..%d, from sw/kat/PQCkemKAT_1632.rsp generated with\n' % nmax)
    fo.write('// pq-crystals/kyber ref (main @ 3edd5af; tvecs512 sha256 matches SHA256SUMS). Select with -DKAT_COUNT=<k>.\n')
    fo.write('// Generated by py/gen_kat_header.py.\n#if (KYBER_K != 2)\n#error "only ML-KEM-512"\n#endif\n')
    fo.write('#ifndef KAT_COUNT\n#define KAT_COUNT 0\n#endif\n')
    for c in range(nmax + 1):
        fo.write(('#if' if c == 0 else '#elif') + f' KAT_COUNT == {c}\n')
        for key, mac in (('seed', 'SEED'), ('pk', 'PK'), ('sk', 'SK'), ('ct', 'CT'), ('ss', 'SS')):
            fo.write(f'#define KYBER_KAT_{mac} "{vec[c][key]}"\n')
    fo.write('#else\n#error "KAT_COUNT out of range (regenerate with a larger max_count)"\n#endif\n')
print(f'{out}: counts 0..{nmax}')
