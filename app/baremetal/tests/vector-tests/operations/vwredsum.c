// vwredsum.vs: sum of the sign-extended vs2 elements and vs1[0] at 2*SEW,
// written to vd[0]. Expected values computed for each case; the sources are
// loaded with SEW equal to their EEW, since RS5 loads still take EEW = SEW.
// vd[0] starts as 0x..a5a5 so that a missing write is caught.

#include "vector_macros.h"

// SEW = 8, LMUL = 1, with negative elements
void TEST_CASE1(void) {
  VSET(16, e8, m1);
  VLOAD_8(v8, 0x37, 0xcb, 0xbb, 0x32, 0xdf, 0x48, 0xb8, 0xd8,
              0xb5, 0x25, 0x5d, 0xaa, 0x10, 0xda, 0xc4, 0xdf);
  VSET(1, e16, m1);
  VLOAD_16(v1, 0x0100);
  VLOAD_16(v2, 0xa5a5);
  VSET(16, e8, m1);
  asm volatile("vwredsum.vs v2, v8, v1");
  VSET(1, e16, m1);
  VCMP_U16(1, v2, 0x0014);
}

